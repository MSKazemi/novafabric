_DEFAULT_CONTROLS = list(_ISO42001_CONTROLS.keys())


class ISO42001Exporter:
    """ISO/IEC 42001:2023 AI Management System evidence package exporter.

    Produces a ZIP containing:

    - ``iso42001-evidence.json``   — structured control-evidence mapping
    - ``control-narratives.json``  — plain-language narratives per clause
    - ``capsule-index.json``       — index of capsules in the audit period
    - ``README.txt``               — human-readable instructions

    Usage::

        exporter = ISO42001Exporter(
            data_dir=Path("capsules"),
            period_start=datetime(2026, 1, 1, tzinfo=timezone.utc),
            period_end=datetime(2026, 6, 30, tzinfo=timezone.utc),
        )
        out = exporter.export(output_path=Path("/tmp/iso42001-package.zip"))
    """

    def __init__(
        self,
        data_dir: Path,
        period_start: datetime,
        period_end: datetime,
    ) -> None:
        self.data_dir = data_dir
        self.period_start = period_start
        self.period_end = period_end

    def export(
        self,
        output_path: Path,
        controls: list[str] | None = None,
    ) -> Path:
        """Export ISO 42001 evidence package as ZIP.

        Args:
            output_path: Path to write the ZIP file.
            controls:    List of clause numbers to include (e.g. ``["6.1", "8.1"]``).
                         Defaults to all supported controls.

        Returns:
            Path to the written ZIP file.
        """
        output_path.parent.mkdir(parents=True, exist_ok=True)
        selected = controls if controls is not None else _DEFAULT_CONTROLS

        # Build control-evidence map
        evidence_map: dict[str, Any] = {}
        for clause in selected:
            ctrl = _ISO42001_CONTROLS.get(clause)
            if ctrl is None:
                evidence_map[clause] = {
                    "title": "Unknown clause",
                    "status": "not_mapped",
                    "narrative": "",
                    "evidence_refs": [],
                }
                continue
            evidence_map[clause] = {
                "title": ctrl["title"],
                "status": "documented",
                "narrative": ctrl["narrative"],
                "evidence_refs": self._gather_evidence_refs(clause),
            }

        # Build capsule index for the audit period
        capsule_index = self._build_capsule_index()

        # Build top-level package document
        package: dict[str, Any] = {
            "@context": "https://novafabric.dev/schemas/iso42001/v1",
            "standard": "ISO/IEC 42001:2023",
            "generated_at": _now_iso_full(),
            "audit_period": {
                "start": self.period_start.isoformat(),
                "end": self.period_end.isoformat(),
            },
            "controls": evidence_map,
            "capsule_count": len(capsule_index),
        }

        readme = (
            "ISO/IEC 42001:2023 AI Management System Evidence Package\n"
            "Generated by NovaFabric\n\n"
            "Contents:\n"
            "  iso42001-evidence.json    — Control-evidence mapping\n"
            "  control-narratives.json   — Plain-language control narratives\n"
            "  capsule-index.json        — Capsule index for audit period\n"
            "  README.txt                — This file\n\n"
            f"Audit period: {self.period_start.date()} to {self.period_end.date()}\n"
            f"Controls included: {', '.join(selected)}\n"
        )

        with zipfile.ZipFile(output_path, "w", zipfile.ZIP_DEFLATED) as zf:
            zf.writestr("iso42001-evidence.json", json.dumps(package, indent=2))
            zf.writestr(
                "control-narratives.json",
                json.dumps(
                    {c: _ISO42001_CONTROLS[c] for c in selected if c in _ISO42001_CONTROLS},
                    indent=2,
                ),
            )
            zf.writestr("capsule-index.json", json.dumps(capsule_index, indent=2))
            zf.writestr("README.txt", readme)

        return output_path

    # ------------------------------------------------------------------
    # Private helpers
    # ------------------------------------------------------------------

    def _gather_evidence_refs(self, clause: str) -> list[str]:
        """Return a list of evidence references for *clause*."""
        refs: list[str] = []
        if not self.data_dir.exists():
            return refs

        # Collect capsule IDs in the audit period
        for child in sorted(self.data_dir.iterdir()):
            if not child.is_dir():
                continue
            manifest_path = child / "capsule.yaml"
            if not manifest_path.exists():
                continue
            data = yaml.safe_load(manifest_path.read_text())
            if not isinstance(data, dict):
                continue
            created_at_raw = data.get("created_at", "")
            if created_at_raw:
                try:
                    created_at = datetime.fromisoformat(
                        str(created_at_raw).replace("Z", "+00:00")
                    )
                    if self.period_start <= created_at <= self.period_end:
                        run_id = data.get("run_id", child.name)
                        refs.append(f"capsule:{run_id}")
                except ValueError:
                    pass

        return refs

    def _build_capsule_index(self) -> list[dict[str, Any]]:
        """Build an index of capsules within the audit period."""
        index: list[dict[str, Any]] = []
        if not self.data_dir.exists():
            return index

        for child in sorted(self.data_dir.iterdir()):
            if not child.is_dir():
                continue
            manifest_path = child / "capsule.yaml"
            if not manifest_path.exists():
                continue
            data = yaml.safe_load(manifest_path.read_text())
            if not isinstance(data, dict):
                continue
            created_at_raw = data.get("created_at", "")
            if created_at_raw:
                try:
                    created_at = datetime.fromisoformat(
                        str(created_at_raw).replace("Z", "+00:00")
                    )
                    if self.period_start <= created_at <= self.period_end:
                        index.append({
                            "run_id": data.get("run_id", child.name),
                            "asset_name": data.get("asset_name"),
                            "created_at": created_at.isoformat(),
                        })
                except ValueError:
                    pass

        return index
