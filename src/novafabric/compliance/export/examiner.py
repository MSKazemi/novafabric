class PCCPExporter:
    """FDA Predetermined Change Control Plan (PCCP) exporter.

    A PCCP documents planned AI modifications under 21 CFR 880.  This exporter
    compares a ``baseline_capsule`` to a ``proposed_capsule`` and produces a
    three-section JSON document per FDA guidance on PCCP for AI/ML-based
    Software as a Medical Device (SaMD).

    Sections:
      1. Description of Modifications
      2. Modification Protocol (testing approach and acceptance criteria)
      3. Impact Assessment (safety, benefit-risk, risk controls)

    Usage::

        exporter = PCCPExporter(
            baseline_capsule_id="run-v1",
            proposed_capsule_id="run-v2",
            data_dir=Path("capsules"),
        )
        out = exporter.export(output_path=Path("/tmp/pccp.json"))
    """

    def __init__(
        self,
        baseline_capsule_id: str,
        proposed_capsule_id: str,
        data_dir: Path,
    ) -> None:
        self.baseline_capsule_id = baseline_capsule_id
        self.proposed_capsule_id = proposed_capsule_id
        self.data_dir = data_dir

    def export(self, output_path: Path) -> Path:
        """Export the PCCP document as JSON.

        Args:
            output_path: File path to write the PCCP JSON.

        Returns:
            Path to the written file.
        """
        output_path.parent.mkdir(parents=True, exist_ok=True)

        pccp: dict[str, Any] = {
            "@context": "https://novafabric.dev/schemas/pccp/v1",
            "pccp_version": "1.0",
            "generated_at": _now_iso_full(),
            "section_1_description_of_modifications": {
                "baseline_capsule": self.baseline_capsule_id,
                "proposed_capsule": self.proposed_capsule_id,
                "modification_summary": self._compute_modification_summary(),
            },
            "section_2_modification_protocol": {
                "testing_approach": "Automated replay comparison via nova diff",
                "performance_metrics": self._extract_performance_metrics(),
                "acceptance_criteria": "No regression in eval suite scores",
            },
            "section_3_impact_assessment": {
                "safety_impact": "See attached diff report",
                "benefit_risk_analysis": self._extract_benefit_risk(),
                "risk_controls": [
                    "NovaSeal signing",
                    "Rego policy gates",
                    "Maker-checker approval",
                ],
            },
        }

        output_path.write_text(json.dumps(pccp, indent=2), encoding="utf-8")
        return output_path

    # ------------------------------------------------------------------
    # Private helpers
    # ------------------------------------------------------------------

    def _load_capsule_manifest(self, capsule_id: str) -> dict[str, Any]:
        capsule_dir = self.data_dir / capsule_id
        if not capsule_dir.exists():
            # Try treating data_dir as the capsule dir directly for the given ID
            manifest_path = self.data_dir / "capsule.yaml"
            if manifest_path.exists():
                data = yaml.safe_load(manifest_path.read_text())
                return data if isinstance(data, dict) else {}
            return {}
        return _load_manifest(capsule_dir)

    def _compute_modification_summary(self) -> str:
        baseline = self._load_capsule_manifest(self.baseline_capsule_id)
        proposed = self._load_capsule_manifest(self.proposed_capsule_id)

        baseline_model = baseline.get("model_id") or baseline.get("asset_name", "unknown")
        proposed_model = proposed.get("model_id") or proposed.get("asset_name", "unknown")

        if baseline_model == proposed_model:
            return (
                f"Model configuration update: {baseline_model}. "
                "See section 2 for testing protocol and acceptance criteria."
            )
        return (
            f"Model change from {baseline_model!r} to {proposed_model!r}. "
            "See section 2 for testing protocol and acceptance criteria."
        )

    def _extract_performance_metrics(self) -> list[dict[str, Any]]:
        proposed = self._load_capsule_manifest(self.proposed_capsule_id)
        metrics: list[dict[str, Any]] = []

        eval_results = proposed.get("eval_results") or proposed.get("evals", [])
        if isinstance(eval_results, list):
            for ev in eval_results:
                if isinstance(ev, dict):
                    metrics.append({
                        "suite": ev.get("suite_name", "unknown"),
                        "score": ev.get("score"),
                        "threshold": ev.get("threshold"),
                    })

        if not metrics:
            metrics = [
                {
                    "suite": "nova-smoke-v1",
                    "score": None,
                    "threshold": None,
                    "note": "No eval results found in proposed capsule",
                }
            ]
        return metrics

    def _extract_benefit_risk(self) -> str:
        proposed = self._load_capsule_manifest(self.proposed_capsule_id)
        notes = proposed.get("benefit_risk_notes") or proposed.get("release_notes", "")
        if notes:
            return str(notes)
        return (
            "Operator must supply benefit-risk analysis per FDA guidance "
            "on PCCP for AI/ML-based SaMD."
        )


