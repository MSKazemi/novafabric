"""Examiner-mode evidence packet exporters.

Three exporters for regulated-industry and audit contexts:

  BagItExporter   — RFC 8493 BagIt packaging for digital preservation.
  PCCPExporter    — FDA Predetermined Change Control Plan (21 CFR 880).
  ISO42001Exporter — ISO/IEC 42001:2023 AI Management System evidence package.

These exporters are self-contained and do not require server mode or a live
database connection.  They operate on the local capsule data directory.
"""

from __future__ import annotations

import json
import stat
import zipfile
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import yaml

from novafabric._hashutil import sha256_file_hex, sha256_hex

# ---------------------------------------------------------------------------
# Internal helpers
# ---------------------------------------------------------------------------

def _sha256_file(path: Path) -> str:
    """Return the lowercase hex SHA-256 of a file (streamed, memory-bounded)."""
    return sha256_file_hex(path)


def _sha256_bytes(data: bytes) -> str:
    """Return the lowercase hex SHA-256 of *data*."""
    return sha256_hex(data)


def _now_iso() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%d")


def _now_iso_full() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%S.%f") + "Z"


def _load_manifest(capsule_dir: Path) -> dict[str, Any]:
    """Load capsule.yaml from *capsule_dir* (or return empty dict if absent)."""
    path = capsule_dir / "capsule.yaml"
    if not path.exists():
        return {}
    data = yaml.safe_load(path.read_text())
    return data if isinstance(data, dict) else {}


# ---------------------------------------------------------------------------
# BagItExporter — RFC 8493
# ---------------------------------------------------------------------------

_BAGIT_TXT = "BagIt-Version: 1.0\nTag-File-Character-Encoding: UTF-8\n"

_VERIFY_SH = """\
#!/bin/bash
# Offline BagIt verification script — generated by NovaFabric
# Usage: ./verify.sh
set -e
echo "Verifying BagIt manifest..."
while IFS='  ' read -r checksum filepath; do
    actual=$(sha256sum "data/$filepath" | awk '{print $1}')
    if [ "$actual" != "$checksum" ]; then
        echo "FAIL: $filepath"
        exit 1
    fi
done < manifest-sha256.txt
echo "All checksums verified OK"
"""


class BagItExporter:
    """RFC 8493 BagIt packaging exporter.

    Produces a self-contained BagIt ZIP that can be transferred to a digital
    preservation repository (e.g., DSpace, Archivematica) without any
    NovaFabric-specific tooling.

    The bag contains:

    - ``bagit.txt``            — BagIt version and encoding declaration
    - ``bag-info.txt``         — bag metadata (size, date, external identifier)
    - ``manifest-sha256.txt``  — SHA-256 checksums of all ``data/`` files
    - ``tagmanifest-sha256.txt`` — SHA-256 checksums of all tag files
    - ``data/``                — evidence payload (capsule files)
    - ``verify.sh``            — standalone bash script for offline verification

    Usage::

        exporter = BagItExporter(capsule_id="run-abc123", data_dir=Path("capsules/run-abc123"))
        bag_path = exporter.export(output_dir=Path("/tmp/bags"))
    """

    def __init__(self, capsule_id: str, data_dir: Path) -> None:
        self.capsule_id = capsule_id
        self.data_dir = data_dir

    def export(
        self,
        output_dir: Path,
        include_audit_report: bool = True,
        contact_email: str = "",
    ) -> Path:
        """Create a BagIt-format ZIP at ``output_dir/{capsule_id}-bag.zip``.

        Args:
            output_dir:          Directory in which to write the ZIP.
            include_audit_report: If True and ``audit-report.json`` exists in
                                  data_dir, include it in the bag payload.
            contact_email:       Optional contact email written to bag-info.txt.

        Returns:
            Path to the written ZIP file.
        """
        output_dir.mkdir(parents=True, exist_ok=True)
        output_path = output_dir / f"{self.capsule_id}-bag.zip"

        # Collect payload files from the capsule directory
        payload: dict[str, bytes] = {}  # filename (relative to data/) -> bytes

        # Always include capsule manifest if present
        for candidate in ["capsule.yaml", "capsule-manifest.json"]:
            src = self.data_dir / candidate
            if src.exists():
                payload[candidate] = src.read_bytes()

        # Include evidence bundle zip if present
        for zip_path in sorted(self.data_dir.glob("*.zip")):
            if zip_path != output_path:
                payload[zip_path.name] = zip_path.read_bytes()

        # Include audit report
        if include_audit_report:
            audit_path = self.data_dir / "audit-report.json"
            if audit_path.exists():
                payload["audit-report.json"] = audit_path.read_bytes()

        # Compute checksums
        manifest_lines: list[str] = []
        for filename, data in sorted(payload.items()):
            digest = _sha256_bytes(data)
            manifest_lines.append(f"{digest}  {filename}")
        manifest_sha256_content = "\n".join(manifest_lines) + "\n" if manifest_lines else ""

        # Compute total payload size
        total_bytes = sum(len(d) for d in payload.values())

        # Build bag-info.txt
        bag_info_lines = [
            "Bag-Software-Agent: novafabric",
            f"Bag-Size: {total_bytes}",
            f"Bagging-Date: {_now_iso()}",
            f"External-Identifier: {self.capsule_id}",
            "Source-Organization: NovaFabric",
        ]
        if contact_email:
            bag_info_lines.append(f"Contact-Email: {contact_email}")
        bag_info_content = "\n".join(bag_info_lines) + "\n"

        # Tag manifests (checksums of the tag files themselves)
        tag_files = {
            "bagit.txt": _BAGIT_TXT.encode(),
            "bag-info.txt": bag_info_content.encode(),
            "manifest-sha256.txt": manifest_sha256_content.encode(),
        }
        tag_manifest_lines: list[str] = []
        for tagname, tagdata in sorted(tag_files.items()):
            digest = _sha256_bytes(tagdata)
            tag_manifest_lines.append(f"{digest}  {tagname}")
        tag_manifest_sha256_content = "\n".join(tag_manifest_lines) + "\n"

        # Write ZIP
        with zipfile.ZipFile(output_path, "w", zipfile.ZIP_DEFLATED) as zf:
            prefix = self.capsule_id

            # Tag files
            zf.writestr(f"{prefix}/bagit.txt", _BAGIT_TXT)
            zf.writestr(f"{prefix}/bag-info.txt", bag_info_content)
            zf.writestr(f"{prefix}/manifest-sha256.txt", manifest_sha256_content)
            zf.writestr(f"{prefix}/tagmanifest-sha256.txt", tag_manifest_sha256_content)

            # verify.sh — make executable in the ZIP info
            verify_info = zipfile.ZipInfo(f"{prefix}/verify.sh")
            verify_info.compress_type = zipfile.ZIP_DEFLATED
            verify_info.external_attr = (
                stat.S_IRWXU | stat.S_IRGRP | stat.S_IXGRP | stat.S_IROTH | stat.S_IXOTH
            ) << 16
            zf.writestr(verify_info, _VERIFY_SH)

            # Payload data/ directory
            for filename, data in sorted(payload.items()):
                zf.writestr(f"{prefix}/data/{filename}", data)

        return output_path


