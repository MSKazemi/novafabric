"""Single-file offline HTML renderer for a ``CapsuleView`` (ADR-0140 P2).

Emits exactly **one** self-contained ``.html`` file satisfying the normative
contract of ``design/spec/capsule-viewer-v0.md`` Part 2:

- zero external requests — no CDN, fonts, images, scripts, ``fetch``/sockets;
- all CSS inline in ``<style>``; no JavaScript at all (no-JS static tables);
- the ``CapsuleView`` JSON embedded inline in
  ``<script type="application/json" id="capsule-view-data">`` for View-Source
  inspection;
- renders fully from ``file://`` with no server and no build toolchain.

The page is a human-readable *view*, not a cryptographic verifier (D4/D6):
it states plainly that real verification is ``nova verify`` / the signed
Evidence Bundle. Uses Jinja2 (existing Tier-A runtime dependency; ADR-0024).
"""

