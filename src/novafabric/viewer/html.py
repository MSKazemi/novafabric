def render_capsule_view_html(view: dict[str, Any]) -> str:
    """Render a ``CapsuleView`` dict as the self-contained HTML page."""
    env = Environment(autoescape=True)
    template = env.from_string(_TEMPLATE)
    page_title = view.get("title") or f"Capsule {view['capsule']['run_id']}"
    # JSON-escape every "<" (unicode escape u003c) so the embedded payload can
    # never close the <script> block early or introduce markup; it stays valid JSON.
    view_json = json.dumps(view, indent=2, ensure_ascii=False).replace("<", "\\u003c")
    return template.render(view=view, page_title=page_title, view_json=Markup(view_json))


def export_capsule_html(
    capsule_dir: str | Path,
    output: str | Path,
    *,
    title: str | None = None,
) -> tuple[Path, list[str]]:
    """Project *capsule_dir* and write the single self-contained HTML file.

    Returns ``(written_path, warnings)``; read-only on the capsule, never
    blocks on partially readable sections (ADR-0140 D6).
    """
    result = build_capsule_view(capsule_dir, title=title)
    out_path = Path(output)
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(render_capsule_view_html(result.view), encoding="utf-8")
    return out_path, result.warnings
